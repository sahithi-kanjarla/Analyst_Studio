"""Turn review_out/scoreboard.csv into docs/benchmarks.md.

Reads only the scoreboard (synthetic review-pack datasets). Makes no AI call.
Usage: python scripts/export_benchmarks.py [scoreboard.csv] [output.md]
"""
from __future__ import annotations

import csv
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "review_out" / "scoreboard.csv"
OUT = ROOT / "docs" / "benchmarks.md"

HISTORY = """## History before the review pack

These facts come from earlier work. Each measured something different and the
test sets differ, so **none of them is directly comparable** with the review-pack
numbers above, or with each other.

| What was measured | Result |
|---|---|
| Lens evaluation sample of 20 requests, real AI, first run: did the AI's plan match the expected plan | 12/20 plan matches (11/20 full passes) |
| The same Lens sample of 20 requests, real AI, a later run | 13/20 plan matches (13/20 full passes) |
| Token cost of one real run on a Shopify-style file | 112,553 tokens in 33 AI calls |
| Size of the automated test suite | grew from 699 to 1,310 passing tests |
| First review run, R01, rules-only (no AI): figures matching pandas | 9/10 figures, with the order column misdetected |
"""


def num(v, cast=float, default=None):
    try:
        return cast(v)
    except (TypeError, ValueError):
        return default


def fmt(v, nd=1):
    return "n/a" if v is None else f"{v:.{nd}f}"


def row_cells(r):
    return [
        r["date_time"], r["dataset"], r["commit"],
        f'{r["figures_passed"]}/{r["figures_total"]}',
        f'{fmt(num(r["percent_correct"]))}%',
        f'{r["questions_asked"]} asked / {r["questions_needed"]} needed',
        r["tokens"], r["total_seconds"], r["seconds_without_limit_waiting"],
        r["ai_partly_unavailable_stages"],
    ]


HEAD = ["Date", "Dataset", "Commit", "Figures correct", "%", "Questions",
        "Tokens", "Total s", "s without limit waiting", "AI-unavailable stages"]


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main(argv):
    src = Path(argv[1]) if len(argv) > 1 else SRC
    out = Path(argv[2]) if len(argv) > 2 else OUT
    with open(src, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    rows.sort(key=lambda r: r["date_time"])
    real = [r for r in rows if r.get("ai_mode", "").strip() == "real"
            and r.get("status", "complete").strip() == "complete"]
    other = [r for r in rows if r not in real]

    md = ["# Benchmarks", "",
          "Generated by `scripts/export_benchmarks.py` from `review_out/scoreboard.csv`. "
          "Do not edit by hand. Datasets are synthetic review-pack files; no user data is included.", ""]

    md += ["## Every real-AI run", ""]
    md += [table(HEAD, [row_cells(r) for r in real]) if real else "_No real-AI runs yet._", ""]

    by_ds = OrderedDict()
    for r in real:
        by_ds.setdefault(r["dataset"], []).append(r)
    md += ["## Baseline versus latest", "",
           "Earliest real-AI run for each dataset compared with the latest. "
           "A dataset with one run is both baseline and latest.", ""]
    base_rows = []
    for ds, rs in by_ds.items():
        a, b = rs[0], rs[-1]
        pa, pb = num(a["percent_correct"]), num(b["percent_correct"])
        delta = "n/a" if pa is None or pb is None else f"{pb - pa:+.1f}"
        ta, tb = num(a["tokens"], int), num(b["tokens"], int)
        sa, sb = num(a["seconds_without_limit_waiting"]), num(b["seconds_without_limit_waiting"])
        base_rows.append([
            ds, f'{a["commit"]} -> {b["commit"]}', f"{fmt(pa)}% -> {fmt(pb)}%", delta,
            f"{ta} -> {tb}", f"{fmt(sa)} -> {fmt(sb)}",
        ])
    md += [table(["Dataset", "Commit (baseline -> latest)", "Figures correct %",
                  "Change (points)", "Tokens", "s without limit waiting"], base_rows)
           if base_rows else "_No real-AI runs yet._", ""]

    md += ["## Overall per commit (real-AI runs)", "",
           "Figures correct summed over all real-AI runs at that commit.", ""]
    by_c = OrderedDict()
    for r in real:
        p = by_c.setdefault(r["commit"], [0, 0, 0])
        p[0] += num(r["figures_passed"], int, 0)
        p[1] += num(r["figures_total"], int, 0)
        p[2] += 1
    md += [table(["Commit", "Runs", "Figures correct", "%"],
                 [[c, n, f"{a}/{t}", f"{100 * a / t:.1f}%" if t else "n/a"]
                  for c, (a, t, n) in by_c.items()])
           if by_c else "_No real-AI runs yet._", ""]

    md += ["## Not real-AI runs (rules-only, dry-run, incomplete)", "",
           "Shown for completeness only. These never count towards the results above.", ""]
    md += [table(HEAD + ["AI mode", "Status"],
                 [row_cells(r) + [r.get("ai_mode", ""), r.get("status", "")] for r in other])
           if other else "_None._", ""]

    md.append(HISTORY)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(real)} real-AI rows, {len(other)} other)")


if __name__ == "__main__":
    main(sys.argv)
