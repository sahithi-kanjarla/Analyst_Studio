"""The data palette has one source: the `chart-tokens` block of frontend/src/tokens.css.

This script reads that block and writes the two files that need the same colours in a language
that cannot read CSS:

  backend/app/palette.py    the colours matplotlib draws the report, Lens and Power BI charts with
  frontend/src/palette.ts   the colours the browser-drawn charts use

    python scripts/gen_palette.py            # write both files
    python scripts/gen_palette.py --check    # exit 1 if either file is out of date

tests/test_palette.py runs the check, so the three can never drift apart.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "frontend" / "src" / "tokens.css"
PY_OUT = ROOT / "backend" / "app" / "palette.py"
TS_OUT = ROOT / "frontend" / "src" / "palette.ts"

# The fonts a chart is drawn with: the app's own face first, then faces that cover non-Latin
# column names (Hindi, Tamil, Chinese, Arabic ...) wherever the system has one.
FONTS = ["IBM Plex Sans", "Inter", "DejaVu Sans", "Noto Sans", "Noto Sans Devanagari", "Nirmala UI",
         "Segoe UI", "Arial Unicode MS", "Noto Sans CJK SC", "Arial"]

# CSS custom property -> the name the two generated files use for it
NAMES = {
    "chart-panel": "PANEL", "chart-ink": "INK", "chart-muted": "MUTED", "chart-line": "LINE",
    "chart-grid": "GRID", "chart-accent": "ACCENT", "chart-neutral": "NEUTRAL",
    "chart-neutral-soft": "NEUTRAL_SOFT", "chart-good": "GOOD", "chart-caution": "CAUTION",
    "chart-bad": "BAD",
}
CATS = [f"cat-{i}" for i in range(1, 7)]


def read_tokens(text: str) -> dict[str, str]:
    """The `--name: #rrggbb;` pairs between the chart-tokens sentinels."""
    m = re.search(r"chart-tokens:start(.*?)chart-tokens:end", text, re.S)
    if not m:
        raise SystemExit("tokens.css has no chart-tokens:start / chart-tokens:end block")
    found = dict(re.findall(r"--([a-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{6})\s*;", m.group(1)))
    missing = [k for k in [*NAMES, *CATS] if k not in found]
    if missing:
        raise SystemExit(f"tokens.css chart-tokens block is missing: {', '.join(missing)}")
    return {k: v.lower() for k, v in found.items()}


HEAD = ("Generated by scripts/gen_palette.py from the chart-tokens block of "
        "frontend/src/tokens.css.\nDo not edit by hand: edit tokens.css and run the script.")


def python_source(t: dict[str, str]) -> str:
    cats = "\n".join(f'    "{t[c]}",      # {c}' for c in CATS)
    names = "\n".join(f'{NAMES[k]} = "{t[k]}"' for k in NAMES)
    fonts = "\n".join(f'    "{f}",' for f in FONTS)
    return f'''"""The one data palette, shared by every chart this app draws.

{HEAD}

Rule for data: the highlighted or selected mark uses ACCENT, every other mark NEUTRAL. CATEGORICAL
is only for series that genuinely need separate identities; its hue order follows Okabe-Ito, so it
stays readable with colour-blindness.
"""
from __future__ import annotations

{names}

# series colours, in order, for a chart that needs more than one identity
CATEGORICAL = [
{cats}
]

# matplotlib's prop_cycle wants the highlight first and quiet neutrals after it
PALETTE = [ACCENT, NEUTRAL, *CATEGORICAL[1:], NEUTRAL_SOFT]

FONTS = [
{fonts}
]


def rc() -> dict:
    """The matplotlib settings every chart in this app shares."""
    return {{
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "axes.grid.axis": "y", "grid.color": GRID, "grid.alpha": 1.0, "grid.linewidth": 0.8,
        "axes.axisbelow": True,          # the grid sits under the bars, never as white stripes across them
        "font.size": 10, "axes.titlesize": 12, "axes.titleweight": "bold", "axes.titlelocation": "left",
        "figure.dpi": 100,
        "text.color": INK, "axes.labelcolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED,
        "axes.edgecolor": LINE, "figure.facecolor": PANEL, "axes.facecolor": PANEL,
        "font.family": "sans-serif", "font.sans-serif": FONTS,
    }}
'''


def ts_source(t: dict[str, str]) -> str:
    cats = "\n".join(f'  "{t[c]}",      // {c}' for c in CATS)
    names = "\n".join(f'export const {NAMES[k]} = "{t[k]}";' for k in NAMES)
    return f'''/* The one data palette, shared by every chart this app draws.

{HEAD}

Rule for data: the highlighted or selected mark uses ACCENT, every other mark NEUTRAL. CATEGORICAL
is only for series that genuinely need separate identities; its hue order follows Okabe-Ito, so it
stays readable with colour-blindness. */

{names}

/** Series colours, in order, for a chart that needs more than one identity. */
export const CATEGORICAL = [
{cats}
];
'''


def main(argv: list[str]) -> int:
    t = read_tokens(TOKENS.read_text(encoding="utf-8"))
    want = {PY_OUT: python_source(t), TS_OUT: ts_source(t)}
    check = "--check" in argv
    stale = [p for p, s in want.items() if not p.exists() or p.read_text(encoding="utf-8") != s]
    if check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT).as_posix()}")
        print("palette files are up to date" if not stale else "run: python scripts/gen_palette.py")
        return 1 if stale else 0
    for p, s in want.items():
        p.write_text(s, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
