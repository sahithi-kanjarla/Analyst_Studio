"""The one data palette, shared by every chart this app draws.

Generated by scripts/gen_palette.py from the chart-tokens block of frontend/src/tokens.css.
Do not edit by hand: edit tokens.css and run the script.

Rule for data: the highlighted or selected mark uses ACCENT, every other mark NEUTRAL. CATEGORICAL
is only for series that genuinely need separate identities; its hue order follows Okabe-Ito, so it
stays readable with colour-blindness.
"""
from __future__ import annotations

PANEL = "#ffffff"
INK = "#16191d"
MUTED = "#5a636e"
LINE = "#dde1e6"
GRID = "#e9ecef"
ACCENT = "#15567f"
NEUTRAL = "#c2c9d1"
NEUTRAL_SOFT = "#dde2e8"
GOOD = "#0e6b4f"
CAUTION = "#8a5a00"
BAD = "#b0271b"

# series colours, in order, for a chart that needs more than one identity
CATEGORICAL = [
    "#15567f",      # cat-1
    "#d1760c",      # cat-2
    "#2e7d32",      # cat-3
    "#c77aa6",      # cat-4
    "#3a8cc4",      # cat-5
    "#3f4652",      # cat-6
]


def category_colours(labels) -> dict:
    """label -> colour for categories listed in rank order (largest first): the first six take the categorical colours, every other one the quiet neutral.
    The browser charts and the pictures both call this, so a category keeps its colour in every chart."""
    return {str(l): (CATEGORICAL[i] if i < len(CATEGORICAL) else NEUTRAL_SOFT) for i, l in enumerate(labels)}

# matplotlib's prop_cycle wants the highlight first and quiet neutrals after it
PALETTE = [ACCENT, NEUTRAL, *CATEGORICAL[1:], NEUTRAL_SOFT]

FONTS = [
    "IBM Plex Sans",
    "Inter",
    "DejaVu Sans",
    "Noto Sans",
    "Noto Sans Devanagari",
    "Nirmala UI",
    "Segoe UI",
    "Arial Unicode MS",
    "Noto Sans CJK SC",
    "Arial",
]


def rc() -> dict:
    """The matplotlib settings every chart in this app shares."""
    return {
        "axes.spines.top": False, "axes.spines.right": False,
        "axes.grid": True, "axes.grid.axis": "y", "grid.color": GRID, "grid.alpha": 1.0, "grid.linewidth": 0.8,
        "axes.axisbelow": True,          # the grid sits under the bars, never as white stripes across them
        "font.size": 10, "axes.titlesize": 12, "axes.titleweight": "bold", "axes.titlelocation": "left",
        "figure.dpi": 100,
        "text.color": INK, "axes.labelcolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED,
        "axes.edgecolor": LINE, "figure.facecolor": PANEL, "axes.facecolor": PANEL,
        "font.family": "sans-serif", "font.sans-serif": FONTS,
    }
